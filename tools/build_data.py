import json
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / "data" / "kaomoji.json"
DEFAULT_OUTPUT = ROOT / "kao" / "_data.py"


def display_width(text):
    width = 0
    for ch in text:
        # marks, variation selectors and ZWJ occupy no cell
        if unicodedata.category(ch) in ("Mn", "Me", "Cf"):
            continue
        if unicodedata.east_asian_width(ch) in ("W", "F"):
            width += 2
        else:
            width += 1
    return width


def _label(entry):
    if isinstance(entry, dict):
        text = entry.get("text", None)
        if isinstance(text, str) and text:
            return text
    return repr(entry)


def validate_entry(entry):
    if not isinstance(entry, dict):
        raise ValueError("entry is not an object: %r" % entry)
    text = entry.get("text", None)
    if not isinstance(text, str) or text == "":
        raise ValueError("empty text in entry %s" % _label(entry))
    if "\t" in text or "\n" in text or "\r" in text:
        raise ValueError("tab/newline in text of entry %s" % _label(entry))
    tags = entry.get("tags", None)
    if tags is None:
        raise ValueError("missing tags in entry %s" % _label(entry))
    if not isinstance(tags, list) or len(tags) == 0:
        raise ValueError("missing or empty tags in entry %s" % _label(entry))
    for tag in tags:
        if not isinstance(tag, str) or tag == "":
            raise ValueError("empty tag in entry %s" % _label(entry))
        if "\t" in tag or "\n" in tag or "\r" in tag:
            raise ValueError("tab/newline in tags of entry %s" % _label(entry))
    category = entry.get("category", None)
    if not isinstance(category, str) or category == "":
        raise ValueError("missing category in entry %s" % _label(entry))
    if any(c.isspace() for c in category):
        raise ValueError("invalid category in entry %s" % _label(entry))
    return entry


def validate(data):
    if not isinstance(data, list):
        raise ValueError("data is not a list")
    seen = set()
    for entry in data:
        validate_entry(entry)
        text = entry["text"]
        if text in seen:
            raise ValueError("duplicate text in entry %s" % text)
        seen.add(text)
    return data


def build(input_path=DEFAULT_INPUT, output_path=DEFAULT_OUTPUT):
    input_path = Path(input_path)
    output_path = Path(output_path)
    with input_path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    validate(data)
    categories = sorted({entry["category"] for entry in data})
    lines = ["# GENERATED by tools/build_data.py - do not edit", "DATA = ("]
    for entry in data:
        tags = " ".join(entry["tags"])
        lines.append(
            "    (%r, %d, %r, %r),"
            % (entry["text"], display_width(entry["text"]), tags, entry["category"])
        )
    lines.append(")")
    lines.append("CATEGORIES = %r" % (tuple(categories),))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return data


def main(argv=None):
    if argv is None:
        argv = sys.argv[1:]
    input_path = Path(argv[0]) if len(argv) > 0 else DEFAULT_INPUT
    output_path = Path(argv[1]) if len(argv) > 1 else DEFAULT_OUTPUT
    try:
        build(input_path, output_path)
    except Exception as exc:  # noqa: BLE001
        print("build_data: %s" % exc, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
